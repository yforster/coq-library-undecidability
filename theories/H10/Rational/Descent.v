(* (coordinates typed in K, so that all later computations stay in K) *)
Definition T0 : pt rat := Some ((0 : K), (0 : K)).
Definition Td : pt rat := Some (dK, (0 : K)).
Definition Tmd : pt rat := Some (- dK, (0 : K)).

Definition rep (s e b : bool) : pt rat :=
  match s, e, b with
  | false, false, false => None
  | true, false, false => T0
  | false, false, true => Td
  | true, false, true => Tmd
  | true, true, false => Some Q0
  | false, true, false => ec_add (Some Q0) T0
  | true, true, true => ec_add (Some Q0) Td
  | false, true, true => ec_add (Some Q0) Tmd
  end.

