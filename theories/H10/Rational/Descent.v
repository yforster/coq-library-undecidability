    + exfalso; case: H => t [ Ht E ].
      have Hq := z2prime_d.
      case: (val_exists Hq Ht) => k [ w [ Hw Et ] ].
      have Hu' : forall s0 : bool, pu z2d (if s0 then -1 else 1).
      { case; [ rewrite -jz1 -jz_opp | rewrite -jz1 ]; apply: (pu_jz Hq); [ | exact: (nd1 Hq) ].
        move=> D; apply: (nd1 Hq); exact: z2dvd_opp. }
