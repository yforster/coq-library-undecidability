(* The weak Mordell-Weil step for E : y^2 = x^3 - d^2 x over
   F = Q(sqrt2) (PLAN P14a, Phase 2E; paper 05-elliptic.tex, proof of
   Prop ell:rank): the 2-isogeny descent.

   MAIN RESULTS.
   - [weak_MW]: every point R of E(F) is  2 R2 + S  with R2 in E(F) and
     S one of the eight points  O, T0, Td, T-d, Q0, Q0 + T0, Q0 + Td,
     Q0 + T-d  (T0 = (0,0), Td = (d,0), T-d = (-d,0); Q0 the point of
     ExplicitData.v). So E(F)/2E(F) is generated by E[2] and Q0.
   - [Q0_notin_2E_E2]: Q0 is not in 2E(F) + E[2] (sharpness).
   - [reps_distinct_mod2]: the eight representatives are pairwise
     incongruent modulo 2E(F); hence |E(F)/2E(F)| = 8 exactly.

   STRUCTURE (Silverman X.4; the paper's argument, without real places:
   signs at the real embeddings are replaced by the norm and by the
   positivity of the rational part of a sum of squares).
   1. The embedding Z[sqrt2] -> F ([jz], Zsqrt2.v), integer powers [zp],
      q-adic units [pu] and q-integral elements [pint] for a prime
      element q of Z[sqrt2], existence and uniqueness of q-adic
      valuations ([val_exists], [val_uniq]).
   2. The valuation parity lemma ([parity]): on y^2 = x^3 + q^m c0 x,
      with c0 a q-unit, an x of q-adic valuation k has 2k = m, or 3k
      even, or m + k even.
   3. Generic 2-isogeny algebra over any field L with 2 <> 0, for
      y^2 = x^3 + c x: the isogeny [psi c] to y^2 = x^3 - 4c x, the dual
      [phihat c], [phihat (psi P) = 2 P], the connecting map [alpha c]
      (class of x, of c at (0,0), of 1 at O) is a homomorphism into
      L^*/L^*2 ([alpha_hom], via Vieta for the chord), and its kernel is
      the image of the dual isogeny ([ker_alpha], [ker_alpha']).
   4. The images: [imA] (alpha(E(F)) is in the eight classes
      +-1, +-eps, +-d, +-eps d) and [imA'] (alpha'(E'(F)) is trivial),
      from the parity lemma and the factorization lemma of Zsqrt2.v.
   5. Assembly.

   No axioms. *)

