(** * 1. Z[sqrt2] inside F *)

Definition jz (x : Z2) : K := zq (re x) (im x).

Lemma jz_add x y : jz (x + y)%z2 = jz x + jz y.
Proof. by case: x => a b; case: y => c d; rewrite /jz zq_add. Qed.

Lemma jz_mul x y : jz (x * y)%z2 = jz x * jz y.
Proof. by case: x => a b; case: y => c d; rewrite /jz zq_mul. Qed.

Lemma jz_opp x : jz (- x)%z2 = - jz x.
Proof. by case: x => a b; rewrite /jz zq_opp. Qed.

Lemma jz_sub x y : jz (x - y)%z2 = jz x - jz y.
Proof. by rewrite /z2sub jz_add jz_opp. Qed.

Lemma jz1 : jz z21 = 1.
Proof. by rewrite /jz /= zq.unlock zr1 zr0. Qed.

Lemma jz0 : jz z20 = 0.
Proof. by rewrite /jz /= zq.unlock zr0. Qed.

Lemma jz_pow x i : jz (z2pow x i) = jz x ^+ i.
Proof. elim: i => [ | i IH ] /=; [ exact: jz1 | by rewrite jz_mul IH exprS ]. Qed.

Lemma jz_inj x y : jz x = jz y -> x = y.
Proof.
  case: x => a b; case: y => c d; rewrite /jz zq.unlock /= => -[] /zr_inj -> /zr_inj ->.
  by [].
Qed.

Lemma jz_neq0 x : x <> z20 -> jz x != 0.
Proof. move=> H; apply/eqP => E; apply: H; apply: jz_inj; by rewrite E jz0. Qed.

Lemma jz_eq0 x : jz x = 0 -> x = z20.
Proof. move=> E; apply: jz_inj; by rewrite E jz0. Qed.

(* every rational is a quotient of binary integers *)
Lemma int_zr (z : int) : exists a : Z, zr a = z%:~R.
Proof. exists (int_to_Z z); by rewrite zr.unlock Z_to_rat_int. Qed.

Lemma rat_zr (r : rat) : exists a b : Z, b <> 0%ZZ /\ r = zr a / zr b.
Proof.
  case: (int_zr (numq r)) => a Ha; case: (int_zr (denq r)) => b Hb.
  exists a, b; split.
  - move=> E; move: Hb; rewrite E zr0 => /esym /eqP; by rewrite intr_eq0 denq_eq0.
  - by rewrite Ha Hb divq_num_den.
Qed.

(* every element of F is a quotient of elements of Z[sqrt2] *)
Lemma K_frac (x : K) : exists A B : Z2, B <> z20 /\ x = jz A / jz B.
Proof.
  case: x => r s.
  case: (rat_zr r) => a1 [ b1 [ Hb1 -> ] ]; case: (rat_zr s) => a2 [ b2 [ Hb2 -> ] ].
  exists (Z2c (a1 * b2) (a2 * b1)), (z2of (b1 * b2)); split.
  - by move=> -[] /Z.mul_eq_0 [].
  - have Hz1 := zr_neq0 Hb1; have Hz2 := zr_neq0 Hb2.
    have HB : jz (z2of (b1 * b2)) != 0 by apply: jz_neq0 => -[] /Z.mul_eq_0 [].
    apply: (canRL (mulfK HB)).
    rewrite /jz /z2of /= zq.unlock qe_mulE !zr_mul zr0; congr QE; field; by apply/andP.
Qed.

(** * 2. Square classes (in any field) *)

Section sqc.

Variable L : fieldType.
Implicit Types x y : L.

Definition sqc (x y : L) : Prop := exists s : L, s != 0 /\ x = y * s ^+ 2.

Lemma sqc_refl x : sqc x x.
Proof. exists 1; by rewrite oner_neq0 expr1n mulr1. Qed.

Lemma sqc_sym x y : sqc x y -> sqc y x.
Proof.
  case=> s [ Hs -> ]; exists s^-1; rewrite invr_eq0 Hs; split => //.
  by rewrite -mulrA -exprMn mulfV // expr1n mulr1.
Qed.

Lemma sqc_trans x y z : sqc x y -> sqc y z -> sqc x z.
Proof.
  case=> s [ Hs -> ]; case=> t [ Ht -> ]; exists (t * s); rewrite mulf_neq0 //; split => //.
  by rewrite exprMn mulrA.
Qed.

Lemma sqc_mul x y x' y' : sqc x y -> sqc x' y' -> sqc (x * x') (y * y').
Proof.
  case=> s [ Hs -> ]; case=> t [ Ht -> ]; exists (s * t); rewrite mulf_neq0 //; split => //.
  rewrite exprMn; ring.
Qed.

Lemma sqc_sq x s : s != 0 -> sqc (x * s ^+ 2) x.
Proof. move=> Hs; by exists s. Qed.

Lemma sqc_sq1 s : s != 0 -> sqc (s ^+ 2) 1.
Proof. move=> Hs; exists s; by rewrite mul1r. Qed.

Lemma sqc_neq0 x y : y != 0 -> sqc x y -> x != 0.
Proof. move=> Hy [ s [ Hs -> ] ]; by rewrite mulf_neq0 // expf_neq0. Qed.

Lemma sqc_sqr1 x : x != 0 -> sqc 1 (x * x).
Proof. move=> Hx; exists x^-1; rewrite invr_eq0 Hx; split => //; field by rewrite Hx. Qed.

End sqc.

(** * 3. Integer powers *)

Definition zp (x : K) (k : Z) : K :=
  match k with
  | Z0 => 1
  | Zpos p => x ^+ Pos.to_nat p
  | Zneg p => (x ^+ Pos.to_nat p)^-1
  end.

Lemma zp_nat x n : zp x (Z.of_nat n) = x ^+ n.
Proof. case: n => [ | n ] //=; by rewrite SuccNat2Pos.id_succ. Qed.

Lemma zp_opp_nat x n : zp x (- Z.of_nat n) = (x ^+ n)^-1.
Proof. case: n => [ | n ] /=; [ by rewrite invr1 | by rewrite SuccNat2Pos.id_succ ]. Qed.

Lemma zp_split (k : Z) : k = (Z.of_nat (Z.to_nat k) - Z.of_nat (Z.to_nat (- k)))%ZZ.
Proof. lia. Qed.

Lemma zp_sub_nat x (a b : nat) : x != 0 -> zp x (Z.of_nat a - Z.of_nat b) = x ^+ a / x ^+ b.
Proof.
  move=> Hx; case: (leqP b a) => Hab.
  - have -> : (Z.of_nat a - Z.of_nat b = Z.of_nat (a - b))%ZZ.
    { move/ssrnat.leP: Hab => Hab; rewrite -minusE; lia. }
    rewrite zp_nat; apply: (canRL (mulfK (expf_neq0 _ Hx))); by rewrite -exprD subnK.
  - have -> : (Z.of_nat a - Z.of_nat b = - Z.of_nat (b - a))%ZZ.
    { move/ssrnat.ltP: Hab => Hab; rewrite -minusE; lia. }
    rewrite zp_opp_nat; apply: (canRL (mulfK (expf_neq0 _ Hx))).
    have -> : x ^+ b = x ^+ (b - a) * x ^+ a by rewrite -exprD subnK // ltnW.
    by rewrite mulrA mulVf ?mul1r // expf_neq0.
Qed.

Lemma zp_add x k l : x != 0 -> zp x (k + l) = zp x k * zp x l.
Proof.
  move=> Hx; rewrite (zp_split k) (zp_split l).
  set a := Z.to_nat k; set b := Z.to_nat (- k); set c := Z.to_nat l; set e := Z.to_nat (- l).
  have -> : (Z.of_nat a - Z.of_nat b + (Z.of_nat c - Z.of_nat e) =
             Z.of_nat (a + c) - Z.of_nat (b + e))%ZZ by rewrite -!plusE; lia.
  rewrite !zp_sub_nat // !exprD; field by rewrite expf_neq0.
Qed.

Lemma zp_neq0 x k : x != 0 -> zp x k != 0.
Proof. move=> Hx; case: k => [ | p | p ] /=; by rewrite ?oner_neq0 ?invr_eq0 ?expf_neq0. Qed.

Lemma zp1 x : zp x 1 = x.
Proof. by rewrite /= expr1. Qed.

Lemma zp_exp x k n : x != 0 -> zp x k ^+ n = zp x (Z.of_nat n * k).
Proof.
  move=> Hx; elim: n => [ | n IH ]; first by rewrite expr0.
  rewrite exprS IH -zp_add //; congr zp; rewrite Nat2Z.inj_succ Z.mul_succ_l; lia.
Qed.

Lemma zp_mul x k l : x != 0 -> zp x k * zp x l = zp x (k + l).
Proof. move=> Hx; by rewrite zp_add. Qed.

Lemma zp_shift x a n : x != 0 -> zp x a * x * x ^+ n = zp x (a + 1 + Z.of_nat n).
Proof. move=> Hx; by rewrite -zp_mul // -zp_mul // zp1 zp_nat. Qed.

(** * 4. q-adic units and valuations *)

Section qadic.

  Variable q : Z2.
  Hypothesis Hq : z2prime q.

  Local Abbreviation pi := (jz q).

  Lemma pi_neq0 : pi != 0.
  Proof. exact: jz_neq0 (z2prime_neq0 Hq). Qed.

  Definition pu (u : K) : Prop :=
    exists a b : Z2, ~ z2dvd q a /\ ~ z2dvd q b /\ u = jz a / jz b.
  Definition pint (u : K) : Prop :=
    exists a b : Z2, ~ z2dvd q b /\ u = jz a / jz b.

  Lemma nd_neq0 a : ~ z2dvd q a -> a <> z20.
  Proof. move=> H E; apply: H; rewrite E; exact: z2dvd_0. Qed.

  Lemma nd1 : ~ z2dvd q z21.
  Proof. move=> H; apply: (z2prime_nunit Hq); exact: z2dvd_unit z2unit_1 H. Qed.

  Lemma nd_mul a b : ~ z2dvd q a -> ~ z2dvd q b -> ~ z2dvd q (a * b)%z2.
  Proof. exact: z2prime_mul. Qed.

  Lemma jz_nd_neq0 a : ~ z2dvd q a -> jz a != 0.
  Proof. move=> H; exact: jz_neq0 (nd_neq0 H). Qed.

  Lemma pu_neq0 u : pu u -> u != 0.
  Proof. case=> a [ b [ Ha [ Hb -> ] ] ]; by rewrite mulf_neq0 ?invr_eq0 ?jz_nd_neq0. Qed.

  Lemma pu_jz a : ~ z2dvd q a -> pu (jz a).
  Proof. move=> Ha; exists a, z21; by rewrite jz1 divr1; split; [ | split; [ exact: nd1 | ] ]. Qed.

  Lemma pint_jz a : pint (jz a).
  Proof. exists a, z21; by rewrite jz1 divr1; split; [ exact: nd1 | ]. Qed.

  Lemma pu_pint u : pu u -> pint u.
  Proof. case=> a [ b [ _ [ Hb -> ] ] ]; by exists a, b. Qed.

  Lemma pu_mul u w : pu u -> pu w -> pu (u * w).
  Proof.
    case=> a [ b [ Ha [ Hb -> ] ] ]; case=> c [ e [ Hc [ He -> ] ] ].
    exists (a * c)%z2, (b * e)%z2; split; [ exact: nd_mul | split; [ exact: nd_mul | ] ].
    rewrite !jz_mul; field by rewrite !jz_nd_neq0.
  Qed.

  Lemma pint_mul u w : pint u -> pint w -> pint (u * w).
  Proof.
    case=> a [ b [ Hb -> ] ]; case=> c [ e [ He -> ] ].
    exists (a * c)%z2, (b * e)%z2; split; [ exact: nd_mul | ].
    rewrite !jz_mul; field by rewrite !jz_nd_neq0.
  Qed.

  Lemma pu_inv u : pu u -> pu u^-1.
  Proof.
    case=> a [ b [ Ha [ Hb -> ] ] ]; exists b, a; split; [ done | split; [ done | ] ].
    by rewrite invf_div.
  Qed.

  Lemma pu_opp u : pu u -> pu (- u).
  Proof.
    case=> a [ b [ Ha [ Hb -> ] ] ]; exists (- a)%z2, b; split; [ | split; [ done | ] ].
    - move=> [ c Hc ]; apply: Ha; exists (- c)%z2.
      have -> : a = (- (- a))%z2 by z2ring. rewrite Hc; z2ring.
    - by rewrite jz_opp mulNr.
  Qed.

  Lemma pu_exp u n : pu u -> pu (u ^+ n).
  Proof.
    move=> Hu; elim: n => [ | n IH ]; first by rewrite expr0 -jz1; apply: pu_jz nd1.
    by rewrite exprS; apply: pu_mul.
  Qed.

  Lemma pint_pi_exp n : pint (pi ^+ n).
  Proof. rewrite -jz_pow; exact: pint_jz. Qed.

  (* a q-unit plus a multiple of q is a q-unit *)
  Lemma pu_add u t : pu u -> pint t -> pu (u + pi * t).
  Proof.
    case=> a [ b [ Ha [ Hb -> ] ] ]; case=> c [ e [ He -> ] ].
    exists (a * e + q * c * b)%z2, (b * e)%z2; split; [ | split; [ exact: nd_mul | ] ].
    - move=> H; have : z2dvd q (a * e)%z2.
      { have -> : (a * e = (a * e + q * c * b) - q * (c * b))%z2 by z2ring.
        apply: z2dvd_sub; [ exact: H | exists (c * b)%z2; z2ring ]. }
      exact: nd_mul.
    - rewrite jz_add !jz_mul; field by rewrite !jz_nd_neq0.
  Qed.

  Lemma val_core u w n : pu u -> pu w -> pi ^+ n.+1 * u = w -> False.
  Proof.
    case=> a [ b [ Ha [ Hb -> ] ] ]; case=> c [ e [ Hc [ He -> ] ] ] E.
    have E' : jz (z2pow q n.+1 * a * e)%z2 = jz (c * b)%z2.
    { have Hb' := jz_nd_neq0 Hb; have He' := jz_nd_neq0 He.
      rewrite [LHS]jz_mul [jz (_ * a)%z2]jz_mul jz_pow [RHS]jz_mul.
      have E1 : pi ^+ n.+1 * jz a = jz c / jz e * jz b by rewrite -E -mulrA divfK.
      by rewrite E1 mulrAC divfK. }
    have H := jz_inj E'.
    have : z2dvd q (c * b)%z2 by rewrite -H; exists (z2pow q n * a * e)%z2; rewrite /=; z2ring.
    by case/(proj2 (proj2 Hq)).
  Qed.

  Lemma val_uniq u w k l : pu u -> pu w -> zp pi k * u = zp pi l * w -> k = l.
  Proof.
    have key : forall k l u w, pu u -> pu w -> (k < l)%ZZ -> zp pi k * u = zp pi l * w -> False.
    { move=> k' l' u' w' Hu Hw Hlt E.
      have E2 : u' = zp pi (l' - k') * w'.
      { have -> : u' = zp pi (- k') * (zp pi k' * u').
        { by rewrite mulrA zp_mul ?pi_neq0 // Z.add_opp_diag_l mul1r. }
        by rewrite E mulrA zp_mul ?pi_neq0 // Z.add_comm. }
      have E3 : u' = pi ^+ (Z.to_nat (l' - k')) * w'.
      { rewrite E2 -zp_nat; congr (zp _ _ * _); lia. }
      move: E3; case En : (Z.to_nat (l' - k')) => [ | n ] E3; first by lia.
      exact: (val_core Hw Hu (esym E3)). }
    move=> Hu Hw E; case: (Z.lt_total k l) => [ H | [ H | H ] ] //.
    - by case: (key _ _ _ _ Hu Hw H E).
    - by case: (key _ _ _ _ Hw Hu H (esym E)).
  Qed.

  Lemma val_exists x : x != 0 -> exists k u, pu u /\ x = zp pi k * u.
  Proof.
    move=> Hx; case: (K_frac x) => A [ B [ HB Ex ] ].
    have HA : A <> z20 by move=> HA; move: Hx; rewrite Ex HA jz0 mul0r eqxx.
    case: (z2_val q A Hq HA) => i [ A' [ EA HA' ] ].
    case: (z2_val q B Hq HB) => j [ B' [ EB HB' ] ].
    exists (Z.of_nat i - Z.of_nat j)%ZZ, (jz A' / jz B'); split; first by exists A', B'.
    rewrite zp_sub_nat ?pi_neq0 // Ex EA EB !jz_mul !jz_pow.
    have HB'' := jz_nd_neq0 HB'; have Hp := pi_neq0.
    field by rewrite ?HB'' ?expf_neq0.
  Qed.

  (** ** The parity lemma *)

  Lemma parity (c0 u x y : K) (m : nat) (k : Z) : pu c0 -> pu u -> x = zp pi k * u ->
    y ^+ 2 = x ^+ 3 + pi ^+ m * c0 * x ->
    (2 * k = Z.of_nat m)%ZZ \/ (exists j, 2 * j = 3 * k)%ZZ \/ (exists j, 2 * j = Z.of_nat m + k)%ZZ.
  Proof.
    move=> Hc0 Hu Hx Hy.
    have Hp := pi_neq0.
    have Hu0 := pu_neq0 Hu; have Hc00 := pu_neq0 Hc0.
    have Hx0 : x != 0 by rewrite Hx mulf_neq0 // zp_neq0.
    have Ek2 : zp pi k ^+ 2 = zp pi (2 * k) by rewrite zp_exp.
    have Ek3 : zp pi k ^+ 3 = zp pi (3 * k) by rewrite zp_exp.
    have Em : pi ^+ m = zp pi (Z.of_nat m) by rewrite zp_nat.
    case: (eqVneq y 0) => [ y0 | yn0 ].
    - left; apply: (@val_uniq (u ^+ 2) (- c0)); [ exact: pu_exp | exact: pu_opp | ].
      have H0 : y ^+ 2 = 0 by rewrite y0 expr0n.
      have : x * (x ^+ 2 + pi ^+ m * c0) = 0 by rewrite -H0 Hy; ring.
      move/eqP; rewrite mulf_eq0 (negbTE Hx0) /= addr_eq0 => /eqP E.
      by rewrite -Em mulrN -E Hx exprMn Ek2.
    - case: (val_exists yn0) => j [ w [ Hw Ey ] ].
      have Ey2 : y ^+ 2 = zp pi (2 * j) * w ^+ 2 by rewrite Ey exprMn zp_exp.
      case: (Z.lt_total (3 * k) (Z.of_nat m + k)) => [ Hlt | [ Heq | Hgt ] ].
      + right; left; exists j.
        set n := Z.to_nat (Z.of_nat m - 2 * k - 1).
        have E : x ^+ 3 + pi ^+ m * c0 * x = zp pi (3 * k) * (u ^+ 3 + pi * (pi ^+ n * c0 * u)).
        { have Z2 : pi ^+ m * zp pi k = zp pi (3 * k) * pi * pi ^+ n.
          { rewrite zp_shift // Em zp_mul //; congr zp; rewrite /n; lia. }
          rewrite Hx exprMn Ek3.
          have -> : pi ^+ m * c0 * (zp pi k * u) = (pi ^+ m * zp pi k) * c0 * u by ring.
          rewrite Z2; ring. }
        apply: (@val_uniq (w ^+ 2) (u ^+ 3 + pi * (pi ^+ n * c0 * u))); [ exact: pu_exp | | ].
        * apply: pu_add; [ exact: pu_exp | ].
          apply: pint_mul; [ apply: pint_mul; [ exact: pint_pi_exp | exact: pu_pint ] | exact: pu_pint ].
        * by rewrite -Ey2 -E.
      + left; lia.
      + right; right; exists j.
        set n := Z.to_nat (2 * k - Z.of_nat m - 1).
        have E : x ^+ 3 + pi ^+ m * c0 * x = zp pi (Z.of_nat m + k) * (c0 * u + pi * (pi ^+ n * u ^+ 3)).
        { have Z2 : zp pi k ^+ 3 = zp pi (Z.of_nat m + k) * pi * pi ^+ n.
          { rewrite zp_shift // Ek3; congr zp; rewrite /n; lia. }
          rewrite Hx exprMn Z2.
          have -> : pi ^+ m * c0 * (zp pi k * u) = (pi ^+ m * zp pi k) * c0 * u by ring.
          rewrite Em zp_mul //; ring. }
        apply: (@val_uniq (w ^+ 2) (c0 * u + pi * (pi ^+ n * u ^+ 3))); [ exact: pu_exp | | ].
        * apply: pu_add; [ exact: pu_mul | ].
          apply: pint_mul; [ exact: pint_pi_exp | apply: pu_pint; exact: pu_exp ].
        * by rewrite -Ey2 -E.
  Qed.

End qadic.

(** * 5. Generic 2-isogeny algebra for  y^2 = x^3 + c x *)

Section isogeny.

  Variable L : fieldType.
  Hypothesis two0 : 2%:R != 0 :> L.
  Variable c : L.
  Hypothesis c0 : c != 0.

  Lemma four0 : 4%:R != 0 :> L.
  Proof. by rewrite (_ : 4%:R = 2%:R * 2%:R) ?mulf_neq0 // -natrM. Qed.
  Lemma eight0 : 8%:R != 0 :> L.
  Proof. by rewrite (_ : 8%:R = 2%:R * 4%:R) ?mulf_neq0 ?four0 // -natrM. Qed.

  Ltac nz := solve [ assumption | exact: two0 | exact: four0 | exact: eight0
                   | apply: mulf_neq0; nz | apply: expf_neq0; nz
                   | rewrite invr_eq0; nz | rewrite oppr_eq0; nz ].

  Definition onc (a : L) (p : L * L) : Prop := p.2 ^+ 2 = p.1 ^+ 3 + a * p.1.
  Definition oncP (a : L) (P : option (L * L)) : Prop := if P is Some p then onc a p else True.

  Lemma onc_w a p : onc a p <-> won 0 a 0 p.
  Proof.
    case: p => x y; rewrite /onc /won /fc /=.
    by rewrite mul0r addr0 addr0.
  Qed.

  Lemma oncP_w a P : oncP a P <-> won_pt 0 a 0 P.
  Proof. case: P => [ p | ] //=; exact: onc_w. Qed.

  (* the 2-isogeny  E_a -> E_{-4a},  (x, y) |-> (y^2/x^2, y (a - x^2)/x^2) *)
  Definition psi (a : L) (P : option (L * L)) : option (L * L) :=
    match P with
    | None => None
    | Some (x, y) => if x == 0 then None else Some (y ^+ 2 / x ^+ 2, y * (a - x ^+ 2) / x ^+ 2)
    end.

