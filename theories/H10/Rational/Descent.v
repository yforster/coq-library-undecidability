(** ** The weak Mordell-Weil theorem *)

Theorem weak_MW_w (R : option (K * K)) : oncP (aE : K) R ->
  exists P (s e b : bool), oncP (aE : K) P /\
    R = wadd (K := K) 0 (aE : K) (wadd (K := K) 0 (aE : K) P P) (rep s e b).
Proof.
  move=> HR.
  case: (alpha_class HR) => s [ e [ b HRc ] ].
  pose S : option (K * K) := rep s e b.
  have HS : oncP (aE : K) S := onc_rep s e b.
  have HSw : won_pt (K := K) 0 (aE : K) 0 S := proj1 (oncP_w _ _) HS.
  have HRw : won_pt (K := K) 0 (aE : K) 0 R := proj1 (oncP_w _ _) HR.
  pose R' := wadd (K := K) 0 (aE : K) R (wneg S).
  have HR' : oncP (aE : K) R'.
  { apply/oncP_w; apply: (wadd_on two0K) => //; exact: wneg_on. }
  have HR'c : sqc (alpha (aE : K) R') 1.
  { have HnS : oncP (aE : K) (wneg S) by apply/oncP_w; exact: wneg_on.
    apply: sqc_trans (alpha_hom two0K aE0K HR HnS) _.
    rewrite alpha_neg.
    apply: sqc_trans (sqc_mul HRc (alpha_rep s e b)) _.
    apply: sqc_trans (sqc_cls_mul s e b s e b) _.
    rewrite !addbb cls0; exact: sqc_refl. }
  case: (kerA HR' HR'c) => Q1 [ HQ1 EQ1 ].
  case: (kerA' HQ1) => P [ HP EP ].
  exists P, s, e, b; split; first exact: HP.
  rewrite -(phihat_psi two0K HP) EP EQ1 /R'.
  by rewrite (wadd_cancel' two0K (@nonsing_QF _ rat_sq2) HRw HSw).
Qed.

