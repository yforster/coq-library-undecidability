  (* Vieta: the line y = l x + nu through two points of the curve meets it
     in a third point with x1 x2 x3 = nu^2 *)
  Lemma vieta_gen x1 x2 l nu :
    x1 ^+ 3 + c * x1 - (l * x1 + nu) ^+ 2 = 0 ->
    (x1 != x2 /\ x2 ^+ 3 + c * x2 - (l * x2 + nu) ^+ 2 = 0 \/
     x1 = x2 /\ 3%:R * x1 ^+ 2 + c - 2%:R * l * (l * x1 + nu) = 0) ->
    x1 * x2 * (l ^+ 2 - 0 - x1 - x2) = nu ^+ 2.
  Proof.
    move=> G1 G2.
    set x3 := l ^+ 2 - 0 - x1 - x2.
    set al := c - 2%:R * l * nu - (x1 * x2 + x1 * x3 + x2 * x3).
    set be := x1 * x2 * x3 - nu ^+ 2.
    have I t : t ^+ 3 + c * t - (l * t + nu) ^+ 2 - (t - x1) * (t - x2) * (t - x3) = al * t + be.
    { rewrite /al /be /x3; ring. }
    have I1 : al * x1 + be = 0 by rewrite -I G1; ring.
    have Hal : al = 0.
    { case: G2 => [ [ ne G2 ] | [ e G2 ] ].
      - have I2 : al * x2 + be = 0 by rewrite -I G2; ring.
        have : al * (x1 - x2) = 0.
        { have E : al * (x1 - x2) = (al * x1 + be) - (al * x2 + be) by ring.
          by rewrite E I1 I2 subrr. }
        move/eqP; rewrite mulf_eq0 subr_eq0 (negbTE ne) orbF => /eqP //.
      - rewrite -G2 /al /x3 e; ring. }
    apply/eqP; rewrite -subr_eq0; apply/eqP.
    by move: I1; rewrite Hal mul0r add0r.
  Qed.

