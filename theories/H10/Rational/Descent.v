Lemma cls_inj s e b s' e' b' : sqc (cls s e b) (cls s' e' b') -> s = s' /\ e = e' /\ b = b'.
Proof.
  move=> H.
  have H1 : sqc (cls s e b * cls s' e' b') 1.
  { case: H => t [ Ht -> ]; exists (cls s' e' b' * t); split; first by rewrite mulf_neq0 ?cls_neq0.
    rewrite mul1r; ring. }
  case: (cls_sq1 (sqc_trans (sqc_sym (sqc_cls_mul s e b s' e' b')) H1)) => E1 [ E2 E3 ].
  have AB : forall x y : bool, x (+) y = false -> x = y by case; case.
  by split; [ exact: AB | split; exact: AB ].
Qed.

Theorem reps_distinct_mod2 R2 s e b s' e' b' : on_curve_pt R2 ->
  rep s e b = ec_add (ec_add R2 R2) (rep s' e' b') -> s = s' /\ e = e' /\ b = b'.
Proof.
  move=> /on_curve_pt_onc HR E; apply: cls_inj.
  rewrite !ec_add_wK in E.
  have HRw : won_pt (K := K) 0 (aE : K) 0 R2 := proj1 (oncP_w _ _) HR.
  have H2R : oncP (aE : K) (wadd (K := K) 0 (aE : K) R2 R2) :=
    proj2 (oncP_w _ _) (wadd_on two0K HRw HRw).
  have A1 := alpha_rep s e b.
  have D : sqc (alpha (aE : K) (wadd (K := K) 0 (aE : K) R2 R2)) 1.
  { apply: sqc_trans (alpha_hom two0K aE0K HR HR) _.
    apply: sqc_sym; exact: sqc_sqr1 (alpha_neq0 aE0K R2). }
  have A2 : sqc (alpha (aE : K) (wadd (K := K) 0 (aE : K) (wadd (K := K) 0 (aE : K) R2 R2) (rep s' e' b')))
                (cls s' e' b').
  { apply: sqc_trans (alpha_hom two0K aE0K H2R (onc_rep s' e' b')) _.
    have := sqc_mul D (alpha_rep s' e' b'); by rewrite mul1r. }
  rewrite E in A1; exact: sqc_trans (sqc_sym A1) A2.
Qed.

Corollary Q0_notin_2E_E2 R2 T : on_curve_pt R2 -> List.In T E2pts ->
  Some Q0 <> ec_add (ec_add R2 R2) T.
